def test_derivation_is_metered(derived):
    conn, report = derived
    rows = conn.execute(
        "SELECT label FROM token_usage WHERE label LIKE 'TAXONOMY:%'"
    ).fetchall()
    assert len(rows) == report.model_calls
    assert any("consolidate" in row["label"] for row in rows)


def test_the_printable_table_names_the_version_and_the_sample(derived):
    conn, report = derived
    table = taxonomy.printable(conn)
    assert report.version in table
    assert str(report.descriptions_read) in table
    for category in report.categories:
        assert category.id in table


# --- the interaction the derived taxonomy exposed ----------------------------

def test_the_activity_track_cannot_crowd_out_an_audit_prior(seeded):
    """The candidate shortlist is capped, so what fills it decides what is seen.

    Capping on age alone let the activity track win on volume: it produces
    hundreds of findings a year against the audit track's dozens, so twelve
    slots filled with system-generated descriptions and the auditor-written
    prior that is the real recurrence never reached the model. Invisible while
    the taxonomy was hardcoded, because activity findings piled into a category
    the audit track barely used; deriving the categories redistributed them and
    recall fell from 50% to 16.7%.
    """
    from datetime import datetime, timedelta

    from sentinelops.entities import Finding
    from sentinelops.llm.prompts.recurrence import MAX_CANDIDATES
    from sentinelops.repositories import simulated_clock

    taxonomy.derive(seeded, AS_OF)
    intelligence.classify(seeded, AS_OF)
    repo = repositories(seeded)

    subject = next(
        f for f in sorted(repo["findings"].list(), key=lambda f: f.raised_at,
                          reverse=True)
        if f.source == "audit" and f.gap_category
    )
    prior = next(
        f for f in repo["findings"].list()
        if f.source == "audit"
        and f.gap_category == subject.gap_category
        and f.raised_at < subject.raised_at
        and f.id != subject.id
    )

    # bury it under far more activity-track findings, all older, all sharing
    # the category — exactly the shape a full pipeline run produces
    oldest = min(f.raised_at for f in repo["findings"].list())
    with simulated_clock(oldest):
        for n in range(MAX_CANDIDATES * 3):
            repo["findings"].add(Finding(
                id=f"FND-NOISE-{n:03d}",
                source="activity_assessment",
                auditable_unit_id="AREA-FINANCE",
                description="Generated description from a control clause.",
                raised_by="ID-SYSTEM",
                raised_at=oldest - timedelta(days=n + 1),
                owner_identity=subject.owner_identity,
                target_date=subject.target_date,
                gap_category=subject.gap_category,
                severity="Minor",
            ))

    shortlist = intelligence.candidates_for(repo, subject)
    assert len(shortlist) <= MAX_CANDIDATES
    assert prior.id in {f.id for f in shortlist}, (
        "an auditor-written prior was pushed off the shortlist by activity-track "
        "volume; the model never gets to see the recurrence it is there to find"
    )
