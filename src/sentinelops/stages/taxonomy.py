def current(conn) -> list[GapCategory]:
    """The frozen set, newest version. Empty until something has derived one."""
    from ..repositories import repositories

    rows = repositories(conn)["categories"].list()
    if not rows:
        return []
    newest = max(rows, key=lambda c: (c.derived_at, c.taxonomy_version))
    return sorted(
        (c for c in rows if c.taxonomy_version == newest.taxonomy_version),
        key=lambda c: c.id,
    )


def names(conn) -> tuple[str, ...]:
    return tuple(c.id for c in current(conn))


def definitions(conn) -> dict[str, str]:
    return {c.id: c.definition for c in current(conn)}


def version(conn) -> str:
    rows = current(conn)
    return rows[0].taxonomy_version if rows else ""


def require(conn) -> list[GapCategory]:
    """The taxonomy, or a refusal that says what to do about it."""
    rows = current(conn)
    if not rows:
        raise ValueError(
            "no gap taxonomy has been derived; run taxonomy.derive() before "
            "classifying. There is deliberately no hardcoded fallback — a "
            "silent default list is the thing this stage exists to remove"
        )
    return rows


def printable(conn) -> str:
    """The derived set, for a human to read and argue with."""
    rows = current(conn)
    if not rows:
        return "no taxonomy derived"
    width = max(len(c.id) for c in rows)
    lines = [
        f"taxonomy {rows[0].taxonomy_version}  "
        f"({len(rows)} categories, read off {rows[0].derived_from_count} "
        f"audit findings, prompt {rows[0].prompt_version})",
        "",
    ]
    for category in rows:
        lines.append(f"  {category.id:<{width}}  {category.definition}")
        if category.merged_from:
            lines.append(
                f"  {'':<{width}}  merged: {', '.join(category.merged_from)}"
            )
    return "\n".join(lines)
